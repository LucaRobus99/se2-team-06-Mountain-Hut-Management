import crypto from 'node:crypto';

/**
 * Password hashing with scrypt (Node's built-in crypto, no extra dependency).
 *
 * Stored format: `scrypt$<salt hex>$<hash hex>`, with a unique 16-byte salt
 * per password and a 64-byte derived key. Plaintext passwords are never stored
 * or accepted: `verifyPassword` only understands this format.
 */
const KEY_LENGTH = 64;
const SALT_BYTES = 16;
const SCRYPT_OPTIONS = { N: 16384, r: 8, p: 1 };
const HASH_PATTERN = /^scrypt\$[0-9a-f]{32}\$[0-9a-f]{128}$/;

export function hashPassword(password) {
  if (typeof password !== 'string' || password === '') {
    throw new TypeError('password must be a non-empty string');
  }
  const salt = crypto.randomBytes(SALT_BYTES).toString('hex');
  const hash = crypto.scryptSync(password, salt, KEY_LENGTH, SCRYPT_OPTIONS).toString('hex');
  return `scrypt$${salt}$${hash}`;
}

export function isPasswordHash(value) {
  return typeof value === 'string' && HASH_PATTERN.test(value);
}

export function verifyPassword(stored, input) {
  if (!isPasswordHash(stored) || typeof input !== 'string') return false;
  try {
    const [, salt, expected] = stored.split('$');
    const derived = crypto.scryptSync(input, salt, KEY_LENGTH, SCRYPT_OPTIONS).toString('hex');
    return crypto.timingSafeEqual(Buffer.from(derived, 'hex'), Buffer.from(expected, 'hex'));
  } catch {
    return false;
  }
}

/**
 * MH-07 (#36): the initial password of a staff-created account is always
 * generated by the server, never chosen by the employee. Characters that are
 * easy to confuse when read aloud or written down (0/O, 1/l/I) are omitted so
 * the password can be communicated verbally.
 */
const TEMPORARY_PASSWORD_ALPHABET =
  'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789';

export function generateTemporaryPassword(length = 14) {
  if (!Number.isInteger(length) || length < 8 || length > 64) {
    throw new RangeError('length must be an integer between 8 and 64');
  }

  let password = '';
  // randomInt is unbiased, unlike `randomBytes[i] % alphabet.length`.
  for (let i = 0; i < length; i += 1) {
    password += TEMPORARY_PASSWORD_ALPHABET[crypto.randomInt(TEMPORARY_PASSWORD_ALPHABET.length)];
  }
  return password;
}

/** Tokens are stored as SHA-256 hashes so a database leak cannot reset accounts. */
export function hashToken(token) {
  return crypto.createHash('sha256').update(String(token)).digest('hex');
}
